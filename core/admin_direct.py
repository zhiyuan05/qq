"""管理员直连动作识别。

管理员私聊时不必再写 ``#``：命中明确的操作意图就交给 AdminAgent 解析；
普通聊天、提问和否定句不拦截。
"""
from __future__ import annotations

import re

_QUESTION = re.compile(r"^\s*(?:怎么|如何|为什么|为啥|什么是|教程|我想知道|在哪|哪里)")
_NEGATION = re.compile(r"(?:不要|别|不用|不需要|无需|禁止)\s*(?:重启|删除|踢|禁言|改|设置|发|执行|写)")

_ACTION_PATTERNS = (
    # 昵称 / 群名片
    r"(?:改|设置|换|起)(?:一下)?(?:昵称|网名|名字|群名片|群昵称)",
    r"(?:昵称|网名|群名片|群昵称).{0,8}(?:改成|设为|换成|叫)",
    r"(?:把|将).{0,12}(?:昵称|网名|群名片|群昵称).{0,8}(?:改|设置|换)",
    # 签名 / 状态
    r"(?:改|设置|换)(?:一下)?(?:签名|个性签名)",
    r"(?:签名|个性签名).{0,8}(?:改成|设为|换成)",
    r"(?:设置|改|切换)(?:一下)?(?:在线状态|状态)",
    # 好友 / 群
    r"(?:列出|看看|查看|查一下|有多少).{0,6}(?:好友|群)",
    r"(?:好友|群).{0,4}(?:列表|有多少)",
    r"(?:群|好友).{0,8}(?:成员|人数)",
    # 群管理
    r"(?:发|发布|设置).{0,4}(?:群公告|公告)",
    r"(?:禁言|踢人|踢出|全员禁言)",
    r"(?:设置|改|给).{0,10}(?:群名片|管理员)",
    # 发消息 / 点赞 / 空间
    r"(?:给|向|帮).{0,12}(?:发消息|发文件|发图片|发语音)",
    r"(?:给|帮).{0,8}(?:点赞|赞一下)",
    r"(?:发|看|删除|查看).{0,4}(?:说说|空间|qzone)",
    # 服务 / 文件 / 命令 / 配置
    r"(?:重启|重载|重新构建|重建|迁移)(?:一下)?(?:服务|机器人|容器|系统)?",
    r"(?:看|查看|读取|导出).{0,4}(?:日志|服务状态)",
    r"(?:改|设置|修改).{0,4}配置",
    r"(?:写|创建|删除|修改).{0,4}文件",
    r"(?:执行|运行).{0,4}(?:命令|脚本)",
    # 人设内容
    r"(?:新建|创建|增加|添加|修改|更新|删除|改).{0,6}(?:人设|角色卡|人格)",
    r"(?:人设|角色卡|人格).{0,8}(?:新建|创建|修改|更新|删除|改成|正文|规则|描述)",
)


class AdminDirectAgent:
    """规则型分流器：只决定是否交给 AdminAgent，不执行任何动作。"""

    def matches(self, text: str) -> bool:
        stripped = text.strip()
        if not stripped or len(stripped) > 200:
            return False
        if _QUESTION.match(stripped) or _NEGATION.search(stripped):
            return False
        return any(re.search(pattern, stripped, re.IGNORECASE) for pattern in _ACTION_PATTERNS)
